  /** Returns a command to run a quasistatic test in the specified direction. */
  public Command sysIdQuasistatic(SysIdRoutine.Direction direction) {
    return run(() -> runCharacterization(0.0))
        .withTimeout(1.0)
        .andThen(sysId.quasistatic(direction));
  }

  /** Returns a command to run a dynamic test in the specified direction. */
  public Command sysIdDynamic(SysIdRoutine.Direction direction) {
    return run(() -> runCharacterization(0.0)).withTimeout(1.0).andThen(sysId.dynamic(direction));
  }

  /** Returns a command to run a quasistatic test in the specified direction. */
  public Command SysIdQuasistatic(SysIdRoutine.Direction direction) {
    return sysIdRoutine.quasistatic(direction);
  }

  public Command SysIdDynamic(SysIdRoutine.Direction direction) {
    return sysIdRoutine.dynamic(direction);
  }

  /** Returns the module states (turn angles and drive velocities) for all of the modules. */
  @AutoLogOutput(key = "SwerveStates/Measured")
  private SwerveModuleState[] getModuleStates() {
    SwerveModuleState[] states = new SwerveModuleState[4];
    for (int i = 0; i < 4; i++) {
      states[i] = modules[i].getState();
    }
    return states;
  }

  // 新增：获取“规范化”后的模块状态，其角度与上一次优化后的目标角度对齐
  @AutoLogOutput(key = "SwerveStates/MeasuredNormalized")
  private SwerveModuleState[] getNormalizedModuleStates() {
    SwerveModuleState[] measuredStates = getModuleStates(); // 获取原始实测状态
    SwerveModuleState[] normalizedStates = new SwerveModuleState[4];

    for (int i = 0; i < 4; i++) {
      SwerveModuleState measured = measuredStates[i];
      // 如果存在上次的优化目标，则将实测角度对齐到该目标附近
      if (m_lastOptimizedSetpoints[i] != null) {
        // 核心：将实测角度调整到与上次优化目标角度最接近的等效角度
        Rotation2d optimizedAngle = m_lastOptimizedSetpoints[i].angle;
        Rotation2d normalizedAngle = normalizeAngle(measured.angle, optimizedAngle);
        normalizedStates[i] = new SwerveModuleState(measured.speedMetersPerSecond, normalizedAngle);
      } else {
        // 没有历史目标，则直接使用原始值（通常只在初始化时）
        normalizedStates[i] = measured;
      }
    }
    return normalizedStates;
  }

  // 新增：角度规范化辅助函数
  // 将 `angleToNormalize` 调整到与 `referenceAngle` 最接近的 2π 区间内
  private Rotation2d normalizeAngle(Rotation2d angleToNormalize, Rotation2d referenceAngle) {
    double normalizedRadians =
        MathUtil.inputModulus(
            angleToNormalize.getRadians(),
            referenceAngle.getRadians() - Math.PI,
            referenceAngle.getRadians() + Math.PI);
    return new Rotation2d(normalizedRadians);
  }

  /** Returns the module positions (turn angles and drive positions) for all of the modules. */
  private SwerveModulePosition[] getModulePositions() {
    SwerveModulePosition[] states = new SwerveModulePosition[4];
    for (int i = 0; i < 4; i++) {
      states[i] = modules[i].getPosition();
    }
    return states;
  }

